fun tinhDT(chieuDai: Double, chieuRong: Double): Double {
    return chieuDai * chieuRong
}

val dienTich1 = tinhDT(5.0, 3.0)
val dienTich2 = tinhDT(7.2, 4.5)
 
fun main() {
    println("Dien tich hinh chu nhat 1: $dienTich1")
    println("Dien tich hinh chu nhat 2: $dienTich2")
}